# Contoh sederhana supervised learning menggunakan aturan prediksi.
# Data contoh: jumlah jam belajar dan nilai ujian.
# Ini hanya ilustrasi konsep, bukan model Deep Learning.

jam_belajar = [1, 2, 3, 4, 5]
nilai_sebenarnya = [50, 55, 65, 70, 80]

# Aturan prediksi sederhana untuk ilustrasi
def prediksi(jam):
    return 40 + (8 * jam)

prediksi_nilai = [prediksi(jam) for jam in jam_belajar]

print("Jam belajar       :", jam_belajar)
print("Nilai sebenarnya  :", nilai_sebenarnya)
print("Nilai prediksi    :", prediksi_nilai)

# Menghitung selisih absolut antara prediksi dan nilai sebenarnya
